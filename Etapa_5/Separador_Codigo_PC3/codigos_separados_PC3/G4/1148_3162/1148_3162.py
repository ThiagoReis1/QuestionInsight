r = input("Qual o nome da regiao?")

if(r == "Norte"):
	print("Snow")
elif(r == "Vale"):
	print("Stone")
elif(r == "Terras Fluviais"):
	print("Rivers")
elif(r == "Terras da Tempestade"):
	print("Storm")
elif(r == "Dorne"):
	print("Sand")
elif(r == "Ilhas de Ferro"):
	print("Pyke")
elif(r == "Campina"):
	print("Flowers")
elif(r == "Terras Ociddentais"):
	print("Hill")
elif(r == "Terras da Coroa"):
	print("Waters")
else:
	print("Entrada", r, "invalida")