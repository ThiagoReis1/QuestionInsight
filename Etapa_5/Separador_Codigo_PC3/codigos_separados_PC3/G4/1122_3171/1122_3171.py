bas = input("Informe o nome do bastardo: ")

if(bas == "Snow"):
	print("Norte")
elif(bas == "Stone"):
	print("Vale")
elif(bas == "Rivers"):
	print("Terras Fluviais")
elif(bas == "Storm"):
	print("Terras da Tempestade")
elif(bas == "Sand"):
	print("Dorne")
elif(bas == "Pyke"):
	print("Ilhas de Ferro")
elif(bas == "Flowers"):
	print("Campina")
elif(bas == "Hill"):
	print("Terras Ocidentais")
elif(bas == "Waters"):
	print("Terras da Coroa")
else:
	print("Entrada",bas,"invalida")
