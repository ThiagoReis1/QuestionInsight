s= input("Digite o sobrenome do bastardo:")

if (s == "Snow"):
	print("Norte")
elif (s == "Stone"):
	print("Vale")
elif (s == "Rivers"):
	print("Terras Fluviais")
elif (s == "Storm"):
	print("Terras da Tempestade")
elif (s == "Sand"):
	print("Dorne")
elif (s == "Pyke"):
	print("Ilhas de Ferro")
elif (s == "Flowers"):
	print("Campina")
elif (s == "Hill"):
	print("Terras Ocidentais")
elif (s == "Waters"):
	print("Terras da coroa")
else:
	print("Entrada", s, "invalida")