p = input("Digite o Bastardo: ")

if ( p == "Snow"):
	print("Norte")
elif (p == "Stone"):
	print("Vale")
elif (p == "Rivers"):
	print("Terras Fluviais")
elif (p == "Storm"):
	print("Terras da Tempestade")
elif (p == "Sand"):
	print("Dorne")
elif (p == "Pyke"):
	print("Ilhas de Ferros")
elif (p == "Flowers"):
	print("Campina")
elif (p == "Hill"):
	print("Terras Ocidentais")
elif (p == "Waters"):
	print("Terras da Coroa")
else:
	print("Entrada", p, "invalida")