nome=(input("nome:"))
if nome.upper()=="SNOW":
	print("Norte")
elif nome.upper()=="STONE":
	print("Vale")
elif nome.upper()=="RIVERS":
	print("Terras Fluviais")
elif nome.upper()=="STORM":
	print("Terras da Tempestade")
elif nome.upper()=="SAND":
	print("Dorne")
elif nome.upper()=="PYKE":
	print("Ilhas de Ferro")
elif nome.upper()=="FLOWERS":
	print("Campina")
elif nome.upper()=="HILL":
	print("Terras Ocidentais")
elif nome.upper()=="WATERS":
	print("Terras da Coroa")
else:
	print("Entrada",nome,"invalida")
	