r = input("Digite o sobrenome:")
if r == "Snow":
	print("Norte")
elif r == "Stone":
	print("Vale")
elif r == "Rivers":
	print("Terras Fluviais")
elif r == "Storm":
	print("Terras da Tempestade")
elif r == "Sand":
	print("Dorne")
elif r == "Pyke":
	print("Ilhas de Ferro")
elif r == "Flowers":
	print("Campina")
elif r == "Hill":
	print("Terras Ocidentais")
elif r == "Waters":
	print("Terras da Coroa")
else:
	print("Entrada", r,"invalida")