n = input("sobrenome: ")

if (n.upper() == "SNOW"):
	print("Norte")
elif (n.upper() == "STONE"):
	print("Vale")
elif (n.upper() == "RIVERS"):
	print("Terras Fluviais")
elif (n.upper() == "STORM"):
	print("Terras da Tempestade")
elif (n.upper() == "SAND"):
	print("Dorne")
elif (n.upper() == "PYKE"):
	print("Ilhas de Ferro")
elif (n.upper() == "FLOWERS"):
	print("Campina")
elif (n.upper() == "HILL"):
	print("Terras Ocidentais")
elif (n.upper() == "WATERS"):
	print("Terras da Coroa")
else:
	print("Entrada", n,"invalida")


