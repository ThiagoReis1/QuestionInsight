personagem = input("Digite: ")

if (personagem != "Joffrey") and (personagem != "Robert") and (personagem != "Sandor") and (personagem != "Theon") and (personagem != "Cersei") and (personagem != "Jaime") and (personagem != "Tyrion") and (personagem != "Jorah") and (personagem != "Jon"):
	print("Entrada", personagem, "invalida")
else: 
	if (personagem == "Joffrey"):
		print("Jack Gleeson")
	elif (personagem == "Robert"):
		print ("Mark Addy")
	elif (personagem == "Sandor"):
		print("Rory McCann")
	elif (personagem == "Theon"):
		print("Alfie Allen" )
	elif (personagem == "Cersei"):
		print("Lena Headey" )
	elif (personagem == "Jaime"):
		print("Nikolaj Coster-Waldau")
	elif (personagem == "Tyrion"):
		print("Peter Dinklage")
	elif (personagem == "Jorah"):
		print("Iain Glen")
	elif (personagem == "Jon"):
		print("Kit Harington")