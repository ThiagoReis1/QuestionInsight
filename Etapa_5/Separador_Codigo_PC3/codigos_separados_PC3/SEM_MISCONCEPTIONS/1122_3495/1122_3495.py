nome1=input()
nome=(nome1.upper())
if (nome=="SNOW"):
	print("Norte")
elif (nome=="STONE"):
	print("Vale")
elif (nome=="RIVERS"):
	print("Terras Fluviais")
elif (nome=="STORM"):
	print("Terras da Tempestade")
elif (nome=="SAND"):
	print("Dorne")
elif (nome=="PYKE"):
	print("Ilhas de Ferro")
elif (nome=="FLOWERS"):
	print("Campina")
elif (nome=="HILL"):
	print("Terras Ocidentais")
elif (nome=="WATERS"):
	print("Terras da Coroa")
else:
	print("Entrada",nome1,"invalida")